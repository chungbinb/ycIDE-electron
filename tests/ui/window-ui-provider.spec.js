const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { test, expect } = require('@playwright/test')
const { launchIsolatedApp } = require('./helpers/launch-app')
const { closeAppDiscardingChanges } = require('./helpers/close-app')
const { switchThemeFromMenu } = require('./helpers/theme-token-coverage-fixtures')
const { createEuiControlLibrary } = require('../fixtures/eui-control-library.cjs')

test('窗口提供者选择、实验确认、控件身份保存及不兼容平台拒绝', async ({}, testInfo) => {
  test.skip(process.platform !== 'win32' || !fs.existsSync(path.resolve(__dirname, '../../lib/eui/sdk/lib/cmake/EuiNeo/EuiNeoConfig.cmake')),
    'Requires the explicitly prepared Windows EUI SDK')
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ycide-provider-ui-'))
  const { app, userData } = await launchIsolatedApp()
  try {
    const page = await app.firstWindow()
    await page.locator('.titlebar').waitFor()
    createEuiControlLibrary(userData, path.resolve(__dirname, '../..'))
    const loaded = await page.evaluate(async () => { await window.api.library.scan(); return window.api.library.load('fixturecontrols') })
    expect(loaded.success).toBe(true)
    expect((await page.evaluate(() => window.api.library.load('script'))).success).toBe(true)
    await switchThemeFromMenu(page, '默认浅色')
    await page.getByRole('menuitem', { name: '文件(F)', exact: true }).click()
    await page.getByRole('menuitem', { name: /新建项目/ }).click()
    const dialog = page.getByRole('dialog', { name: '新建项目' })
    await expect(dialog).toBeVisible()
    const providers = dialog.getByLabel('窗口 UI 支持库：', { exact: true })
    await expect(providers).toBeEnabled()
    await dialog.getByRole('button', { name: /Linux/ }).click()
    await expect(dialog.getByRole('alert')).toContainText('没有可用')
    await expect(dialog.getByRole('button', { name: '确认创建项目' })).toBeDisabled()
    await dialog.getByRole('button', { name: /Windows/ }).click()
    await expect(providers.locator('option[value="ycide.krnln.win32"]')).toBeEnabled()
    await providers.selectOption('ycide.krnln.win32')
    await providers.selectOption('ycide.eui.selfdraw')
    await expect(dialog.getByRole('button', { name: '确认创建项目' })).toBeDisabled()
    await providers.focus()
    await page.keyboard.press('Tab')
    const acceptance = dialog.getByRole('checkbox', { name: /我了解这是实验后端/ })
    await expect(acceptance).toBeFocused()
    expect(await acceptance.evaluate(element => parseFloat(getComputedStyle(element).outlineWidth))).toBeGreaterThan(0)
    await page.keyboard.press('Space')
    await dialog.getByLabel('项目名称：', { exact: true }).fill('EUI测试')
    await dialog.locator('.np-path-row input').fill(directory)
    await dialog.getByRole('button', { name: '确认创建项目' }).focus()
    await page.keyboard.press('Enter')
    await expect(page.locator('.vd-form-canvas')).toBeVisible()
    await expect(page.getByRole('status', { name: '' }).filter({ hasText: 'EUI 实验后端' })).toBeVisible()
    const projectDir = path.join(directory, 'EUI测试')
    const epp = path.join(projectDir, 'EUI测试.epp')
    expect(fs.readFileSync(epp, 'utf8')).toContain('UiProvider=ycide.eui.selfdraw')
    expect(fs.readFileSync(epp, 'utf8')).toContain('Compiler=ycide.eui-msvc')
    await page.getByLabel('组件分类').selectOption({ label: 'EUI自绘控件' })
    await page.getByRole('button', { name: 'EUI按钮 (eui)', exact: true }).click()
    await page.locator('.vd-form-canvas').click({ position: { x: 100, y: 120 } })
    await expect(page.locator('.vd-eui-preview-button')).toBeVisible()
    await page.keyboard.press('Control+s')
    const formPath = path.join(projectDir, '_启动窗口.efw')
    await expect.poll(() => JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[0]?.typeId).toBe('EuiButton')
    expect(JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[0].libraryId).toBe('eui')
    await page.getByLabel('组件分类').selectOption({ label: '跨库测试控件' })
    await page.getByRole('button', { name: 'EUI按钮 (fixturecontrols)', exact: true }).click()
    await page.locator('.vd-form-canvas').click({ position: { x: 100, y: 190 } })
    await expect(page.locator('.vd-eui-preview-button')).toHaveCount(2)
    await expect(page.locator('select[title="选择并加入事件处理子程序"] option').filter({ hasText: '外库单击' })).toHaveCount(1)
    await page.keyboard.press('Control+s')
    await expect.poll(() => JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[1]?.libraryId).toBe('fixturecontrols')
    expect(JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[1].typeId).toBe('EuiButton')
    await page.getByLabel('组件分类').selectOption({ label: '功能组件' })
    await page.getByRole('button', { name: '脚本组件 (script)', exact: true }).click()
    await page.locator('.vd-form-canvas').click({ position: { x: 300, y: 120 } })
    await expect(page.locator('.vd-preview-compact')).toHaveCount(1)
    await page.getByRole('button', { name: '编辑语言，当前值 JScript', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.getByRole('textbox', { name: '编辑语言', exact: true }).fill('VBScript')
    await page.getByRole('textbox', { name: '编辑语言', exact: true }).press('Enter')
    await page.getByRole('button', { name: '编辑超时，当前值 0', exact: true }).focus()
    await page.keyboard.press('Enter')
    const timeout = page.getByRole('textbox', { name: '编辑超时', exact: true })
    await timeout.fill('1500')
    await timeout.press('Tab')
    await page.keyboard.press('Control+s')
    await expect.poll(() => JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[2]?.properties).toEqual({ 语言: 'VBScript', 超时: 1500 })
    expect(JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[2]).toMatchObject({ libraryId: 'script', typeId: 'Script', width: 32, height: 32 })
    await page.getByLabel('组件分类').selectOption({ label: 'Win32控件' })
    await page.getByRole('button', { name: '选择框 (krnln)', exact: true }).click()
    await page.locator('.vd-form-canvas').click({ position: { x: 420, y: 120 } })
    await expect(page.locator('.vd-preview-checkbox')).toBeVisible()
    await page.getByRole('button', { name: '滑块条 (krnln)', exact: true }).click()
    await page.locator('.vd-form-canvas').click({ position: { x: 420, y: 180 } })
    await expect(page.locator('.vd-preview-slider')).toBeVisible()
    await page.keyboard.press('Control+s')
    expect(JSON.parse(fs.readFileSync(formPath, 'utf8')).controls.slice(3).map(control => control.typeId)).toEqual(['CheckBox', 'SliderBar'])
    await page.getByLabel('目标平台', { exact: true }).selectOption('linux')
    await expect(page.getByRole('alert')).toContainText('不支持目标平台 linux')
    await expect(page.locator('.vd-control-unsupported')).toHaveCount(5)
    expect(fs.readFileSync(epp, 'utf8')).toContain('Platform=linux')
    await page.getByLabel('目标平台', { exact: true }).selectOption('windows')
    await expect(page.locator('.vd-control-unsupported')).toHaveCount(0)
    const units = await page.evaluate(directory => window.api.library.getWindowUnits('windows', directory), projectDir)
    expect(units.some(unit => unit.libraryName === 'fixturecontrols')).toBe(true)
    expect(units.some(unit => unit.libraryName === 'script' && unit.englishName === 'Script')).toBe(true)
    expect(units.some(unit => unit.libraryName === 'krnln' && unit.englishName === 'CheckBox')).toBe(true)
    await app.evaluate(({ dialog }, filename) => {
      dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [filename] })
    }, epp)
    await page.getByRole('menuitem', { name: '文件(F)', exact: true }).click()
    await page.getByRole('menuitem', { name: /打开项目/ }).first().click()
    await expect(page.locator('.vd-eui-preview-button')).toHaveCount(2)
    await expect(page.locator('.vd-preview-checkbox')).toBeVisible()
    await expect(page.locator('.vd-preview-slider')).toBeVisible()
    await expect(page.locator('.vd-preview-compact')).toHaveCount(1)
    await page.locator('.vd-preview-compact').click()
    await expect(page.getByRole('button', { name: '编辑语言，当前值 VBScript', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: '编辑超时，当前值 1500', exact: true })).toBeVisible()
    expect(JSON.parse(fs.readFileSync(formPath, 'utf8')).controls[0].typeId).toBe('EuiButton')
    for (const theme of ['默认浅色', '默认深色']) {
      await switchThemeFromMenu(page, theme)
      await page.locator('.vd-form-titlebar').click()
      await page.locator('.prop-row', { hasText: '深色主题' }).locator('select').selectOption({ label: theme === '默认深色' ? '真' : '假' })
      const channel = await page.locator('.vd-form-canvas').evaluate(element => Number(getComputedStyle(element).backgroundColor.match(/[\d.]+/g)[0]))
      if (theme === '默认深色') expect(channel).toBeLessThan(50)
      else expect(channel).toBeGreaterThan(200)
      const tokens = JSON.parse(fs.readFileSync(path.resolve(__dirname, '../../lib/eui/theme-tokens.json'), 'utf8'))
      const palette = theme === '默认深色' ? tokens.dark : tokens.light
      const chrome = await page.locator('.vd-eui-window').evaluate(element => {
        const title = element.querySelector('.vd-form-titlebar')
        const canvas = element.querySelector('.vd-form-canvas')
        return {
          titleHeight: title.offsetHeight,
          clientOffset: canvas.offsetTop,
          titleColor: getComputedStyle(title).backgroundColor.match(/[\d.]+/g).slice(0, 3).map(Number),
          buttons: Array.from(title.querySelectorAll('.vd-form-btn')).map(button => ({ text: button.textContent, width: button.offsetWidth })),
          nativeIcon: !!title.querySelector('.vd-form-titlebar-icon'),
        }
      })
      expect(chrome.titleHeight).toBe(tokens.titlebarHeight)
      expect(chrome.clientOffset).toBe(tokens.titlebarHeight)
      expect(chrome.nativeIcon).toBe(false)
      expect(chrome.buttons.map(button => button.text)).toEqual(['最小化', '最大化', '关闭'])
      expect(chrome.buttons.every(button => button.width === tokens.captionButtonWidth)).toBe(true)
      chrome.titleColor.forEach((channel, index) => expect(Math.abs(channel - Math.round(palette.surface[index] * 255))).toBeLessThanOrEqual(1))
      const contrast = await page.locator('.vd-eui-preview-button').first().evaluate(element => {
        const style = getComputedStyle(element)
        const luminance = color => {
          const values = color.match(/[\d.]+/g).slice(0, 3).map(Number).map(value => {
            const channel = value / 255
            return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4
          })
          return values[0] * 0.2126 + values[1] * 0.7152 + values[2] * 0.0722
        }
        const text = luminance(style.color)
        const background = luminance(style.backgroundColor)
        return (Math.max(text, background) + 0.05) / (Math.min(text, background) + 0.05)
      })
      expect(contrast).toBeGreaterThanOrEqual(4.5)
      await expect(page.locator('.vd-preview-checkbox')).toBeVisible()
      await expect(page.locator('.vd-preview-slider')).toBeVisible()
      await page.screenshot({ path: testInfo.outputPath(`eui-designer-${theme}.png`) })
    }
  } finally {
    await closeAppDiscardingChanges(app)
    fs.rmSync(directory, { recursive: true, force: true })
    fs.rmSync(userData, { recursive: true, force: true })
  }
})
